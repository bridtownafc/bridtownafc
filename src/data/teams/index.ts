export const isTeamId = (value: unknown): value is TeamId => typeof value === 'string' && value in teams;
export const otherTeam = (id: TeamId): TeamId => (id === 'mens' ? 'womens' : 'mens');

const sectionSegments: Record<Section, string> = { home: '', matches: 'matches/', team: 'team/', news: 'news/' };

export const sectionHref = (team: TeamId, section: Section) => `${teams[team].basePath}${sectionSegments[section]}`;

/** Resolves a link for a team. Shared pages carry `?team=` so the selected team survives the visit. */
export const linkFor = (team: TeamId, target: LinkTarget) =>
  'section' in target ? sectionHref(team, target.section) : `${target.shared}?team=${team}${target.hash ? `#${target.hash}` : ''}`;

export const profileHref = (team: TeamId, player: Player) => `${sectionHref(team, 'team')}${player.slug}/`;

export const photoAlt = (team: Team, player: Player) =>
  player.photo
    ? `${player.name}, Bridlington Town AFC ${team.phrase}, ${player.photo.description}`
    : `Bridlington Town AFC club badge, shown until a photo of ${player.name} is supplied`;

/** Web-optimised 4:5 copies generated by scripts/optimise-squad-photos.mjs. */
export const PHOTO_WIDTHS = [400, 800, 1200] as const;
/** File name stem of a player's generated photos: versioned for CMS photos, so a replaced photo gets new URLs. */
const photoStem = (player: Player) => (player.photo?.version ? `${player.slug}-${player.photo.version}` : player.slug);
export const photoSrcset = (team: Team, player: Player, format: 'webp' | 'jpg') =>
  PHOTO_WIDTHS.map((w) => `${team.photoDir}/web/${photoStem(player)}-${w}.${format} ${w}w`).join(', ');
export const photoFallback = (team: Team, player: Player) => `${team.photoDir}/web/${photoStem(player)}-800.jpg`;

